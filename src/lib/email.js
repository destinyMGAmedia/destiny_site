function nationFromAddress() {
  const fromName = process.env.RESEND_FROM_NAME || 'Destiny Nation'
  const fromEmail = process.env.RESEND_FROM_EMAIL || 'noreply@destinymissionglobal.org'
  return `${fromName} <${fromEmail}>`
}

